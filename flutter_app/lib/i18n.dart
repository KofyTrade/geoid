import 'dart:io';

import 'package:flutter/material.dart';

/// Traducciones de la app. El idioma sigue al del sistema; si no esta en la
/// lista, se usa ingles.
class I18n {
  static final ValueNotifier<String> aviso = ValueNotifier('en');

  static const List<String> soportados = ['en', 'es', 'fr', 'de', 'it', 'ru', 'ja', 'ko'];

  static void iniciar() {
    var codigo = 'en';
    try {
      final locale = Platform.localeName.replaceAll('-', '_');
      final corto = locale.split('_').first.toLowerCase();
      if (soportados.contains(corto)) codigo = corto;
    } catch (_) {
      codigo = 'en';
    }
    aviso.value = codigo;
  }

  static String get idioma => aviso.value;

  /// Fija el idioma a mano; null = volver al del sistema.
  static void fijar(String? codigo) {
    if (codigo == null || codigo.isEmpty) {
      iniciar();
      return;
    }
    aviso.value = soportados.contains(codigo) ? codigo : 'en';
  }

  static String t(String clave) {
    final tabla = _textos[idioma] ?? _textos['en']!;
    return tabla[clave] ?? _textos['en']![clave] ?? clave;
  }
}

